"""Compile the project skill into runtime guidance and existing method cards."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re
import sqlite3

ROOT = Path(__file__).resolve().parents[1]
PATTERNS = (
    ("validation", "Validation and time", ["task_contract", "temporal", "temporal_group", "distribution_shift"]),
    ("representation", "Lost feature information", ["text", "feature_engineering", "label_conflicts"]),
    ("sparse", "Rare entities, missingness and zeros", ["rare_classes", "high_cardinality", "missingness_shift"]),
    ("decision", "Decision metric and output", ["rare_classes", "class_imbalance", "threshold", "calibration"]),
    ("cost", "Cost and ablation", ["budget", "ensemble", "hpo"]),
)


def compile_skill(root=ROOT):
    source = root / "skills/qwen-ml-best-practices"
    skill = (source / "SKILL.md").read_text()
    patterns = (source / "references/diagnostic-patterns.md").read_text()
    body = skill.split("---", 2)[2].strip()
    guide = body.split("## Conditional patterns", 1)[0].strip()
    sections = dict(re.findall(r"^## ([^\n]+)\n(.*?)(?=^## |\Z)", patterns, re.M | re.S))
    identifiers = {key: "human_practice_" + key for key, _, _ in PATTERNS}
    guide += "\n\nConditional patterns are available in the local methods collection. Read only a relevant one:\n"
    guide += "\n".join(f"- method:{identifiers[key]}: {title}" for key, title, _ in PATTERNS)
    guide += ("\nUse search_knowledge/read_knowledge and their returned references. "
        "Do not invent a filesystem tool. Missing material is a knowledge gap, not evidence. "
        "These patterns propose tests; no particular model or positive result is required.\n")
    hashes = {name: hashlib.sha256((source / name).read_bytes()).hexdigest()
        for name in ("SKILL.md", "references/diagnostic-patterns.md")}
    module = ('"""Generated by tools/build_human_practice.py from the project skill."""\n'
        + "SOURCE_HASHES = " + repr(hashes) + "\nGUIDE = " + repr(guide) + "\n")
    cards = {}
    for key, title, signals in PATTERNS:
        section = sections[title].strip()
        fields = {}
        for field in ("Signal", "Check", "Candidate experiment", "Limits"):
            match = re.search(r"\*\*" + re.escape(field) + r":\*\* (.*?)(?=\n\n|\Z)", section, re.S)
            if match is None:
                raise ValueError("Missing skill section field: " + title + ":" + field)
            fields[field] = match.group(1)
        identifier = identifiers[key]
        cards[identifier] = {"id": identifier, "method_id": identifier, "version": 1,
            "title": "Human ML practice: " + title,
            "observations": fields["Signal"], "hypothesis": fields["Candidate experiment"],
            "diagnostic": fields["Check"], "minimum_experiment": fields["Candidate experiment"],
            "acceptance": "Evaluate the original metric against a comparable incumbent; disclose uncertainty and full cost.",
            "constraints": fields["Limits"],
            "conditions": ["Confirmed task; all learning is fit-only, including inner folds.",
                "Published cases suggest conditional tests; their results are not measurements on this task."],
            "contraindications": [fields["Limits"]], "cost": "Measure preparation, auxiliary fits, inference and refit.",
            "implementation_path": "mixed", "runtime_status": "unverified", "references": [],
            "missing_references": [], "applicability_rules": [], "tags": signals,
            "related_routing_signals": signals, "skill_id": "qwen-ml-best-practices",
            "skill_source_hashes": hashes, "skill_text": title + "\n\n" + section,
            "research_sources": re.findall(r"\]\((https://[^)]+)\)", section),
            "heuristic_status": "project_hypothesis_not_universal_rule",
            "evidence_policy": "Project synthesis of author reports; no complete human trace or local reproduction is claimed."}
    return module, cards


def build(root=ROOT):
    module, cards = compile_skill(root)
    (root / "automl_agent/human_practice.py").write_text(module)
    for identifier, card in cards.items():
        (root / "ml_knowledge/catalogs/methods" / (identifier + ".json")).write_text(
            json.dumps(card, ensure_ascii=False, sort_keys=True, indent=2) + "\n")
    return {"cards": sorted(cards), "runtime_guide_chars": len(module)}


def extend_frozen(baseline, frozen):
    """Preserve every delivered baseline record; append only the new skill cards."""
    from ml_knowledge.core import canonical, digest, file_hash, read_json, write_json
    lock = read_json(baseline / "knowledge.lock.json")
    with sqlite3.connect("file:" + str((baseline / "knowledge.sqlite").resolve()) + "?mode=ro", uri=True) as db:
        records = {}
        for identifier, meta, text in db.execute("SELECT d.id,d.meta,t.text FROM docs d JOIN texts t ON d.sha=t.sha"):
            record = json.loads(meta)
            record["text"] = text
            records[identifier] = record
    restored = "".join(canonical(records[key]) + "\n" for key in sorted(records))
    if digest(restored) != lock["documents_sha256"]:
        raise ValueError("Baseline records do not reproduce its frozen document hash")
    additions = [json.loads(line) for line in (frozen / "documents.jsonl").read_text().splitlines()
        if json.loads(line).get("payload", {}).get("skill_id") == "qwen-ml-best-practices"]
    if len(additions) != len(PATTERNS) or any(item["id"] in records for item in additions):
        raise ValueError("Expected five new skill records, without baseline replacements")
    records.update({record["id"]: record for record in additions})
    (frozen / "documents.jsonl").write_text("".join(canonical(records[key]) + "\n" for key in sorted(records)))
    inputs = {"documents_sha256": file_hash(frozen / "documents.jsonl"),
        "expected_sha256": file_hash(frozen / "expected.json"),
        "coverage_sha256": file_hash(frozen / "coverage.json"),
        "notices_sha256": file_hash(frozen / "THIRD_PARTY_NOTICES.txt"),
        "requirements_sha256": lock["requirements_sha256"],
        "base_corpus": lock["corpus"], "base_lock_sha256": file_hash(baseline / "knowledge.lock.json"),
        "skill_sources": additions[0]["payload"]["skill_source_hashes"]}
    write_json(frozen / "inputs.lock.json", inputs)
    return {"preserved": len(records) - len(additions), "added": sorted(row["id"] for row in additions)}


if __name__ == "__main__":
    print(json.dumps(build()))
